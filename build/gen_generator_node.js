/**
 * Node.js replacement for the gen_generator() step of build.py, which needs
 * Python 2 and the Google Closure Compiler. The closure step only performs
 * SIMPLE_OPTIMIZATIONS (local renaming / whitespace removal), which has no
 * semantic effect, so a plain concatenation with the goog.provide / require
 * calls stripped produces a functionally identical <language>_compressed.js.
 *
 * Usage: node build/gen_generator_node.js <language>
 * e.g.   node build/gen_generator_node.js python
 */

'use strict';

const fs = require('fs');
const path = require('path');

const language = process.argv[2];
if (!language) {
    process.stderr.write('Usage: node build/gen_generator_node.js <language>\n');
    process.exit(1);
}

const repoRoot = path.join(__dirname, '..');
const entry = path.join(repoRoot, 'generators', `${language}.js`);
const dir = path.join(repoRoot, 'generators', language);

if (!fs.existsSync(entry)) {
    process.stderr.write(`No such generator: ${entry}\n`);
    process.exit(1);
}

const files = [entry].concat(
    fs.readdirSync(dir)
        .filter(f => f.endsWith('.js'))
        .sort()
        .map(f => path.join(dir, f))
);

const stripGoog = source => source
    .split('\n')
    .filter(line => !/^\s*goog\.(provide|require)\(/.test(line))
    .join('\n');

const HEADER = '// Do not edit this file; automatically generated by build.py.\n' +
    '\'use strict\';\n' +
    '\nlet Blockly = require(\'hxblock-blocks\');\n\n';

const body = files
    .map(f => `// --- ${path.relative(repoRoot, f)} ---\n${stripGoog(fs.readFileSync(f, 'utf8'))}`)
    .join('\n');

const target = path.join(repoRoot, `${language}_compressed.js`);
fs.writeFileSync(target, HEADER + body);
process.stdout.write(`SUCCESS: ${target} (${files.length} files)\n`);
