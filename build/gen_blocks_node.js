/**
 * Node.js replacement for the gen_blocks() step of build.py, which needs
 * Python 2 and the Google Closure Compiler. The closure step only performs
 * SIMPLE optimizations (local renaming / whitespace removal), which has no
 * semantic effect, so a plain concatenation with goog.provide / goog.require
 * handled produces a functionally identical blocks_compressed_<type>.js.
 *
 * goog.provide lines cannot simply be dropped like in gen_generator_node.js:
 * block files assign into namespaces such as
 * Blockly.ScratchBlocks.ProcedureUtils directly, and rely on goog.provide
 * having created the object chain. Each provided namespace is therefore
 * expanded into `a = a || {}; a.b = a.b || {};` statements (Blockly itself
 * is injected by the shim, so the root segment is never redeclared).
 *
 * Usage: node build/gen_blocks_node.js <vertical|horizontal|common>
 */

'use strict';

const fs = require('fs');
const path = require('path');

const blockType = process.argv[2];
const sources = {
    vertical: {target: 'blocks_compressed_vertical.js', dir: 'blocks_vertical'},
    horizontal: {target: 'blocks_compressed_horizontal.js', dir: 'blocks_horizontal'},
    common: {target: 'blocks_compressed.js', dir: 'blocks_common'}
};

if (!blockType || !sources[blockType]) {
    process.stderr.write('Usage: node build/gen_blocks_node.js <vertical|horizontal|common>\n');
    process.exit(1);
}

const repoRoot = path.join(__dirname, '..');
const dir = path.join(repoRoot, sources[blockType].dir);

// Same file list and order as build.py gen_blocks(): the block directory
// sorted alphabetically, then core/colours.js and core/constants.js.
const files = fs.readdirSync(dir)
    .filter(f => f.endsWith('.js'))
    .sort()
    .map(f => path.join(dir, f))
    .concat([
        path.join(repoRoot, 'core', 'colours.js'),
        path.join(repoRoot, 'core', 'constants.js')
    ]);

const provided = new Set();

const transform = source => source
    .split('\n')
    .map(line => {
        const provide = line.match(/^\s*goog\.provide\('([^']+)'\);?\s*$/);
        if (provide) {
            // Expand the namespace chain, skipping the root segment which is
            // injected by the shim (Blockly / goog).
            const segments = provide[1].split('.');
            const statements = [];
            for (let i = 2; i <= segments.length; i++) {
                const ns = segments.slice(0, i).join('.');
                if (!provided.has(ns)) {
                    provided.add(ns);
                    statements.push(`${ns} = ${ns} || {};`);
                }
            }
            return statements.join(' ');
        }
        if (/^\s*goog\.require\(/.test(line)) {
            return '';
        }
        return line;
    })
    .join('\n');

const HEADER = '// Do not edit this file; automatically generated by build.py.\n' +
    '\'use strict\';\n\n';

const body = files
    .map(f => `// --- ${path.relative(repoRoot, f)} ---\n${transform(fs.readFileSync(f, 'utf8'))}`)
    .join('\n');

const target = path.join(repoRoot, sources[blockType].target);
fs.writeFileSync(target, HEADER + body);
process.stdout.write(`SUCCESS: ${target} (${files.length} files)\n`);
